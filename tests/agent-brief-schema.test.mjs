import assert from "node:assert/strict";
import test from "node:test";
import {
  dailyBriefOutputSchema,
  dailyBriefSchema,
} from "../lib/agent/brief-schema.ts";

function savedBrief() {
  return {
    greeting: "Good morning.",
    status_line: "Two things need you today.",
    traffic: {
      label: "typical",
      headline: "Typical Wednesday: about 100 drinks expected (90-110), around a normal day.",
      expected_drinks: 100,
      low: 90,
      high: 110,
    },
    stock_items: [{
      ingredient_id: "1",
      name: "Milk",
      headline: "Milk is running low.",
      why: "Below minimum stock.",
      suggested_order: {
        quantity: 2,
        unit: "L",
        supplier: "Sunrise Dairy Co",
        estimated_cost: 3.1,
      },
      approve_action_id: null,
    }],
    all_clear: "1 stock item needs attention: Milk.",
    data_warnings: [],
  };
}

test("model output schema is small and rejects unrelated fields", () => {
  assert.equal(dailyBriefOutputSchema.safeParse({ greeting: "Good morning." }).success, true);
  assert.equal(dailyBriefOutputSchema.safeParse({ greeting: "Good morning.", items: [] }).success, false);
  assert.equal(dailyBriefOutputSchema.safeParse([{ title: "Wrong top-level shape" }]).success, false);
});

test("brief schema rejects cached data generated by the previous agent", () => {
  const cached = savedBrief();
  assert.equal(dailyBriefSchema.safeParse(cached).success, true);
  const oldCachedBrief = { ...cached, items: [], details: { schemaVersion: 3 } };
  assert.equal(dailyBriefSchema.safeParse(oldCachedBrief).success, false);
});

test("brief represents insufficient sales history without inventing traffic numbers", () => {
  const brief = savedBrief();
  brief.traffic = {
    label: null,
    headline: "There's not enough recent sales history to forecast traffic today.",
    expected_drinks: null,
    low: null,
    high: null,
  };
  assert.equal(dailyBriefSchema.safeParse(brief).success, true);
});

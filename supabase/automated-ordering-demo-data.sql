-- Demo-only supplier and delivery data for the automated-ordering agent.
-- Existing ingredients, recipes, and inventory quantities are not changed.
-- Supplier names and prices below are illustrative and must not be used for
-- real purchasing decisions.
begin;

create table if not exists public.incoming_deliveries (
  delivery_id bigint generated by default as identity primary key,
  ingredient_id integer not null references public.ingredients(ingredient_id),
  quantity numeric not null check (quantity >= 0),
  expected_date date not null,
  demo_key text unique
);

create table if not exists public.supplier_prices (
  supplier text not null,
  ingredient_id integer not null references public.ingredients(ingredient_id),
  price numeric not null check (price >= 0),
  delivery_time text not null,
  minimum_order numeric not null default 0 check (minimum_order >= 0),
  primary key (supplier, ingredient_id)
);

alter table public.incoming_deliveries enable row level security;
revoke all on table public.incoming_deliveries from public, anon, authenticated;
grant select, insert, update on table public.incoming_deliveries to service_role;
grant usage, select on sequence public.incoming_deliveries_delivery_id_seq to service_role;

alter table public.supplier_prices enable row level security;
revoke all on table public.supplier_prices from public, anon, authenticated;
grant select on table public.supplier_prices to service_role;

insert into public.supplier_prices
  (supplier, ingredient_id, price, delivery_time, minimum_order)
values
  ('Demo Local Dairy', 1, 0.0042, 'Next day', 1000),
  ('Demo Wholesale Dairy', 1, 0.0048, '2 business days', 1000),
  ('Demo Roaster', 2, 0.0350, 'Next day', 500),
  ('Demo Wholesale Coffee', 2, 0.0380, '2 business days', 500),
  ('Demo Baking Supply', 3, 0.0210, 'Next day', 250),
  ('Demo Wholesale Ingredients', 3, 0.0240, '2 business days', 250)
on conflict (supplier, ingredient_id) do nothing;

-- A small future milk delivery demonstrates that incoming stock is considered.
-- The date moves forward if this script is re-run, so the demo row won't go stale.
insert into public.incoming_deliveries
  (ingredient_id, quantity, expected_date, demo_key)
values
  (1, 5000, current_date + 1, 'automated-ordering-showcase-milk')
on conflict (demo_key) do update
set quantity = excluded.quantity,
    expected_date = excluded.expected_date;

commit;

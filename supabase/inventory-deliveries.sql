-- Prerequisites: inventory-feature.sql and automated-ordering-drafts.sql.
-- No demo data, supplier messages, or stock resets are performed.
begin;

create table if not exists public.delivery_batches (
  id uuid primary key default gen_random_uuid(),
  draft_id uuid not null unique references public.draft_orders(id),
  supplier_reference text not null check (length(btrim(supplier_reference)) between 1 and 120),
  expected_date date not null,
  created_at timestamptz not null default clock_timestamp()
);

create table if not exists public.incoming_deliveries (
  delivery_id bigint generated by default as identity primary key,
  ingredient_id integer not null references public.ingredients(ingredient_id),
  quantity numeric not null check (quantity >= 0),
  expected_date date not null,
  demo_key text unique
);
-- quantity is the original order quantity. Receipts determine the outstanding balance.
alter table public.incoming_deliveries add column if not exists batch_id uuid references public.delivery_batches(id);
alter table public.incoming_deliveries add column if not exists ordered_quantity numeric;
alter table public.incoming_deliveries add column if not exists supplier_name text;
alter table public.incoming_deliveries add column if not exists stock_unit text;
update public.incoming_deliveries set ordered_quantity = quantity where ordered_quantity is null;
update public.incoming_deliveries d set stock_unit = i.unit from public.ingredients i
  where d.ingredient_id = i.ingredient_id and d.stock_unit is null;
create unique index if not exists incoming_delivery_batch_ingredient
  on public.incoming_deliveries(batch_id, ingredient_id) where batch_id is not null;

create table if not exists public.delivery_receipts (
  id uuid primary key,
  delivery_id bigint not null references public.incoming_deliveries(delivery_id),
  ingredient_id bigint not null references public.inventory(ingredient_id),
  ingredient_name text not null,
  unit text not null,
  amount numeric not null check (amount > 0),
  remaining_before numeric not null,
  remaining_after numeric not null check (remaining_after >= 0),
  stock_before numeric not null,
  stock_after numeric not null,
  note text not null,
  movement_id bigint not null unique references public.inventory_movements(id),
  created_at timestamptz not null default clock_timestamp()
);

alter table public.delivery_batches enable row level security;
alter table public.delivery_receipts enable row level security;
alter table public.incoming_deliveries enable row level security;
revoke all on public.delivery_batches, public.delivery_receipts, public.incoming_deliveries from public, anon, authenticated;
grant select, insert on public.delivery_batches, public.delivery_receipts to service_role;
grant select, insert, update on public.incoming_deliveries to service_role;
grant usage, select on sequence public.incoming_deliveries_delivery_id_seq to service_role;

-- Approval alone does not mean goods have been ordered. A staff member calls
-- this only after placing the order outside this application.
create or replace function public.register_order_delivery(
  p_draft_id uuid, p_expected_date date, p_reference text
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_draft public.draft_orders%rowtype;
  v_batch public.delivery_batches%rowtype;
  v_line jsonb;
  v_id bigint;
  v_quantity numeric;
  v_unit text;
  v_supplier text;
begin
  if p_draft_id is null or p_expected_date is null or p_reference is null
    or length(btrim(p_reference)) not between 1 and 120 then raise exception 'INVALID_DELIVERY'; end if;
  select * into v_draft from public.draft_orders where id = p_draft_id for update;
  if not found or v_draft.status <> 'approved' then raise exception 'ORDER_NOT_APPROVED'; end if;
  select * into v_batch from public.delivery_batches where draft_id = p_draft_id;
  if found then
    if v_batch.expected_date <> p_expected_date or v_batch.supplier_reference <> btrim(p_reference) then
      raise exception 'ORDER_ALREADY_REGISTERED';
    end if;
    return jsonb_build_object('batch_id', v_batch.id, 'replayed', true);
  end if;
  if jsonb_typeof(v_draft.lines) is distinct from 'array'
    or jsonb_array_length(v_draft.lines) not between 1 and 100 then raise exception 'INVALID_ORDER_LINES'; end if;
  insert into public.delivery_batches(draft_id, expected_date, supplier_reference)
    values (p_draft_id, p_expected_date, btrim(p_reference)) returning * into v_batch;
  for v_line in select value from jsonb_array_elements(v_draft.lines) loop
    if coalesce(v_line->>'ingredientId','') !~ '^[0-9]{1,18}$'
      or coalesce(v_line->>'recommendedOrderQuantity','') !~ '^[0-9]+(\.[0-9]{1,6})?$' then
      raise exception 'INVALID_ORDER_LINES';
    end if;
    v_id := (v_line->>'ingredientId')::bigint;
    v_quantity := (v_line->>'recommendedOrderQuantity')::numeric;
    v_supplier := v_line->'recommendedSupplier'->>'supplier';
    if v_quantity <= 0 or v_quantity > 1000000000 or v_supplier is null
      or length(btrim(v_supplier)) not between 1 and 120 then raise exception 'INVALID_ORDER_LINES'; end if;
    select unit into v_unit from public.ingredients where ingredient_id = v_id;
    if not found or v_unit is null or btrim(v_unit) = ''
      or v_unit is distinct from v_line->>'unit' then raise exception 'ORDER_UNIT_MISMATCH'; end if;
    if not exists(select 1 from public.inventory where ingredient_id = v_id) then raise exception 'NO_STOCK_RECORD'; end if;
    if exists(select 1 from public.incoming_deliveries where batch_id = v_batch.id and ingredient_id = v_id) then
      raise exception 'INVALID_ORDER_LINES';
    end if;
    insert into public.incoming_deliveries(ingredient_id, quantity, ordered_quantity, expected_date, batch_id, supplier_name, stock_unit)
      values(v_id, v_quantity, v_quantity, p_expected_date, v_batch.id, v_supplier, v_unit);
  end loop;
  return jsonb_build_object('batch_id', v_batch.id, 'replayed', false);
end;
$$;

create or replace function public.receive_inventory_delivery(
  p_request_id uuid, p_delivery_id bigint, p_amount numeric,
  p_expected_remaining numeric, p_note text
) returns jsonb language plpgsql security invoker set search_path = '' as $$
declare
  v_delivery public.incoming_deliveries%rowtype;
  v_receipt public.delivery_receipts%rowtype;
  v_stock numeric;
  v_updated timestamptz;
  v_movement bigint;
  v_name text;
  v_unit text;
  v_replayed boolean := false;
  v_remaining numeric;
begin
  if p_request_id is null or p_delivery_id is null or p_amount is null or p_amount <= 0
    or p_amount > 1000000000 or p_amount::text in ('NaN','Infinity','-Infinity')
    or p_amount <> trunc(p_amount, 6) or p_expected_remaining is null
    or p_expected_remaining <= 0 or p_expected_remaining::text in ('NaN','Infinity','-Infinity')
    or p_note is null or length(btrim(p_note)) not between 1 and 120 then raise exception 'INVALID_RECEIPT'; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(p_request_id::text, 0));
  select * into v_receipt from public.delivery_receipts where id = p_request_id;
  if found then
    if v_receipt.delivery_id <> p_delivery_id or v_receipt.amount <> p_amount
      or v_receipt.remaining_before <> p_expected_remaining or v_receipt.note <> btrim(p_note) then
      raise exception 'RECEIPT_REQUEST_CONFLICT';
    end if;
    v_replayed := true;
  else
    select * into v_delivery from public.incoming_deliveries where delivery_id = p_delivery_id for update;
    if not found then raise exception 'DELIVERY_NOT_FOUND'; end if;
    select greatest(0, v_delivery.quantity - coalesce(sum(amount), 0)) into v_remaining
      from public.delivery_receipts where delivery_id = p_delivery_id;
    if v_remaining is distinct from p_expected_remaining then raise exception 'DELIVERY_CHANGED'; end if;
    if p_amount > v_remaining then raise exception 'EXCEEDS_OUTSTANDING'; end if;
    select ingredient_name, unit into v_name, v_unit from public.ingredients where ingredient_id = v_delivery.ingredient_id;
    if not found or v_name is null or v_unit is null or btrim(v_unit) = '' then raise exception 'INVALID_INGREDIENT'; end if;
    if v_delivery.stock_unit is distinct from v_unit then raise exception 'ORDER_UNIT_MISMATCH'; end if;
    select quantity_in_stock, last_updated into v_stock, v_updated
      from public.inventory where ingredient_id = v_delivery.ingredient_id for update;
    if not found then raise exception 'NO_STOCK_RECORD'; end if;
    if v_stock is null or v_stock < 0 or v_stock::text in ('NaN','Infinity','-Infinity') then raise exception 'INVALID_STOCK'; end if;
    update public.inventory set quantity_in_stock = v_stock + p_amount,
      last_updated = greatest(clock_timestamp(), v_updated + interval '1 millisecond')
      where ingredient_id = v_delivery.ingredient_id;
    insert into public.inventory_movements(ingredient_id, kind, amount, quantity_before, quantity_after, note)
      values(v_delivery.ingredient_id, 'delivery', p_amount, v_stock, v_stock + p_amount,
        'Receipt ' || p_request_id::text || ': ' || btrim(p_note)) returning id into v_movement;
    insert into public.delivery_receipts(id, delivery_id, ingredient_id, ingredient_name, unit, amount,
      remaining_before, remaining_after, stock_before, stock_after, note, movement_id)
      values(p_request_id, p_delivery_id, v_delivery.ingredient_id, v_name, v_unit, p_amount,
        v_remaining, v_remaining - p_amount, v_stock, v_stock + p_amount, btrim(p_note), v_movement)
      returning * into v_receipt;
  end if;
  return jsonb_build_object('receipt_id', v_receipt.id, 'name', v_receipt.ingredient_name, 'unit', v_receipt.unit,
    'amount', v_receipt.amount::text, 'before', v_receipt.stock_before::text, 'after', v_receipt.stock_after::text,
    'remaining', v_receipt.remaining_after::text, 'replayed', v_replayed);
end;
$$;

revoke all on function public.register_order_delivery(uuid,date,text) from public, anon, authenticated;
revoke all on function public.receive_inventory_delivery(uuid,bigint,numeric,numeric,text) from public, anon, authenticated;
grant execute on function public.register_order_delivery(uuid,date,text) to service_role;
grant execute on function public.receive_inventory_delivery(uuid,bigint,numeric,numeric,text) to service_role;
commit;
